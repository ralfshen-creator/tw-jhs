window.QUESTION_CONCEPT = {};
window.conceptOf = function (q) {
  const list = window.CONCEPTS[q.chapter] || [];
  const want = q.concept || window.QUESTION_CONCEPT[q.id];
  if (want) { const c = list.find(x => x.id === want); if (c) return c; }
  const text = [q.q, (q.options || []).join(" "), q.explain || ""].join(" ");
  let best = null, bestScore = 0;
  list.forEach(c => {
    const score = c.kw.reduce((s, k) => s + (q.q.includes(k) ? 3 : 0) + (text.includes(k) ? 1 : 0), 0);
    if (score > bestScore) { best = c; bestScore = score; }
  });
  return best;
};
